// Builds supabase/sift-ai-one-file.ts: the sift-ai Edge Function as a single file, for pasting into the
// Supabase dashboard editor. Run `npm run function:one-file` (node scripts/one-file-function.mjs --write) after changing supabase/functions/sift-ai/.
import { readFileSync, writeFileSync } from 'node:fs';

const ROOT = new URL('../', import.meta.url);
export const outFile = (root = ROOT) => new URL('supabase/sift-ai-one-file.ts', root);

/** `root`: the repository folder as a file URL (ending in /). */
export function oneFile(root = ROOT) {
  const dir = new URL('supabase/functions/sift-ai/', root);
  const index = readFileSync(new URL('index.ts', dir), 'utf8'), lib = readFileSync(new URL('lib.ts', dir), 'utf8');
  const libImport = /^import \{[^}]*\} from '\.\/lib\.ts';\n/m;
  if (!libImport.test(index)) throw new Error("index.ts no longer imports './lib.ts' on one line");
  const lines = index.replace(libImport, '').split('\n');
  const lastImport = lines.findLastIndex(l => l.startsWith('import '));
  return [
    '// GENERATED by scripts/one-file-function.mjs from supabase/functions/sift-ai/{index,lib}.ts. Do not edit by hand.',
    '// For the Supabase dashboard: Edge Functions → new function named "sift-ai" → paste this whole file → deploy (keep Verify JWT on).',
    '// It needs the secret SIFT_ANTHROPIC_API_KEY (or ANTHROPIC_API_KEY). See docs/SETUP.md, step 7.',
    '',
    ...lines.slice(0, lastImport + 1),
    '',
    '// ---- lib.ts ----',
    lib.trimEnd(),
    '',
    '// ---- index.ts ----',
    ...lines.slice(lastImport + 1),
  ].join('\n');
}

if (process.argv.includes('--write')) {
  writeFileSync(outFile(), oneFile()); console.log('wrote supabase/sift-ai-one-file.ts');
}
